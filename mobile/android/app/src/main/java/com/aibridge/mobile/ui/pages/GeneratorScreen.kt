/**
 * M4 生成器（A5.1 密码生成 + A5.2 口令词模式；默认 20 位 · 不存生成历史）。
 *
 * 薄入口：字符集、词表规则、长度约束、熵值计算全在 core（Vault.generate /
 * Vault.generatePassphrase，熵源经注入的 Entropy）；本屏只收集参数并展示结果。
 * 强度条（A5.1）：只显示 core 返回的 `entropy_bits` 数值并按 UI 阈值分档，不重新计算。
 * 明文纪律：不存生成历史 —— 本屏不保留任何历史状态，离开即失（docs/功能点全景.md §5）。
 * 待确认（绑定命名待生成后核对）：`PassphraseSpec` 字段名（words / word_count / separator）、
 * `generate_passphrase` 的对象归属、`entropy_bits` 的 FFI 暴露形态（命名空间函数 / Vault 方法）
 * 待 mobile/ffi 落地后校准；本文件按 UniFFI 惯例命名调用，校准点集中在本文件 import 与
 * entropyBitsOf 两处。
 */
@Composable
fun GeneratorScreen(
    dependencies: AppDependencies,
    modifier: Modifier = Modifier,
) {
    var passphraseMode by remember { mutableStateOf(false) }
    var length by remember { mutableStateOf(20) }
    var lowercase by remember { mutableStateOf(true) }
    var uppercase by remember { mutableStateOf(true) }
    var digits by remember { mutableStateOf(true) }
    var symbols by remember { mutableStateOf(true) }
    var wordsText by remember { mutableStateOf("") }
    var wordCount by remember { mutableStateOf(4) }
    var separator by remember { mutableStateOf("-") }
    var generated by remember { mutableStateOf<GeneratedSecret?>(null) }
    var generatedPassphrase by remember { mutableStateOf<String?>(null) }
    var entropyBits by remember { mutableStateOf(0u) }
    var errorMessage by remember { mutableStateOf<String?>(null) }
    val context = LocalContext.current

    PageScaffold(screenId = "M4", title = "生成器（默认 20 位 · 不存历史）", functionPoints = "A5", modifier = modifier) {
        Column(modifier = Modifier.verticalScroll(rememberScrollState())) {
            Text(text = "模式", style = MaterialTheme.typography.titleMedium)
            Row(verticalAlignment = Alignment.CenterVertically) {
                RadioButton(selected = !passphraseMode, onClick = { passphraseMode = false })
                Text("字符")
                RadioButton(selected = passphraseMode, onClick = { passphraseMode = true })
                Text("口令词")
            }

            if (passphraseMode) {
                Text(text = "参数（A5.2）", style = MaterialTheme.typography.titleMedium)
                OutlinedTextField(
                    value = wordsText,
                    onValueChange = { wordsText = it },
                    label = { Text("词表（每行一个词）") },
                    modifier = Modifier.fillMaxWidth(),
                )
                Row(verticalAlignment = Alignment.CenterVertically) {
                    OutlinedButton(onClick = { if (wordCount > 1) wordCount -= 1 }) { Text("−") }
                    Text(text = "词数：$wordCount", modifier = Modifier.padding(horizontal = 8.dp))
                    OutlinedButton(onClick = { if (wordCount < 24) wordCount += 1 }) { Text("＋") }
                }
                OutlinedTextField(
                    value = separator,
                    onValueChange = { separator = it },
                    label = { Text("分隔符") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth(),
                )
                Text(
                    text = "词表 / 词数 / 分隔符由本机配置提供（core 不内置词表、不设默认）。",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            } else {
                Text(text = "参数（A5.1）", style = MaterialTheme.typography.titleMedium)
                Row(verticalAlignment = Alignment.CenterVertically) {
                    OutlinedButton(onClick = { if (length > 8) length -= 1 }) { Text("−") }
                    Text(text = "长度：$length 位", modifier = Modifier.padding(horizontal = 8.dp))
                    OutlinedButton(onClick = { if (length < 64) length += 1 }) { Text("＋") }
                }
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Switch(checked = lowercase, onCheckedChange = { lowercase = it })
                    Text("小写")
                    Switch(checked = uppercase, onCheckedChange = { uppercase = it })
                    Text("大写")
                }
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Switch(checked = digits, onCheckedChange = { digits = it })
                    Text("数字")
                    Switch(checked = symbols, onCheckedChange = { symbols = it })
                    Text("符号")
                }
            }

            Button(onClick = {
                try {
                    if (passphraseMode) {
                        val spec = PassphraseSpec(
                            words = wordsText.split('\n').map { it.trim() }.filter { it.isNotEmpty() },
                            wordCount = wordCount.toUInt(),
                            separator = separator,
                        )
                        generatedPassphrase = dependencies.core.vault().generatePassphrase(spec)
                        generated = null
                        entropyBits = entropyBitsOf(spec)
                    } else {
                        val spec = GeneratorSpec(
                            length = length.toUInt(),
                            lowercase = lowercase,
                            uppercase = uppercase,
                            digits = digits,
                            symbols = symbols,
                        )
                        generated = dependencies.core.vault().generate(spec)
                        generatedPassphrase = null
                        entropyBits = entropyBitsOf(spec)
                    }
                    errorMessage = null
                } catch (e: Exception) {
                    errorMessage = "生成失败（${errorText(e)}）"
                }
            }, modifier = Modifier.fillMaxWidth()) {
                Text("生成")
            }

            val result = generated?.value ?: generatedPassphrase
            if (result != null) {
                Text(text = "结果", style = MaterialTheme.typography.titleMedium)
                Text(text = result, style = MaterialTheme.typography.bodyLarge)
                generated?.let { secret ->
                    Text(
                        text = "字符集：${secret.charset}",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }

                // 强度条（A5.1）：只显示 core 返回的熵值并分档，不在 UI 重算。
                Text(
                    text = "强度：${entropyBits} bit（${strengthLabel(entropyBits)}）",
                    style = MaterialTheme.typography.bodySmall,
                )
                LinearProgressIndicator(
                    progress = { (entropyBits.toFloat() / 128f).coerceIn(0f, 1f) },
                    modifier = Modifier.fillMaxWidth(),
                )

                OutlinedButton(onClick = {
                    context.getSystemService(ClipboardManager::class.java)
                        .setPrimaryClip(ClipData.newPlainText("生成结果", result))
                }) { Text("复制") }
            }

            errorMessage?.let { message ->
                Spacer(modifier = Modifier.height(8.dp))
                Text(text = message, color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall)
            }

            Spacer(modifier = Modifier.height(8.dp))
            Text(
                text = "不保存生成历史（明文纪律）。",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
    }
}

/** 强度分档阈值（UI 自定，仅显示用；判定与计算在 core）。 */
private fun strengthLabel(bits: UInt): String = when {
    bits < 40u -> "弱"
    bits < 60u -> "中"
    bits < 80u -> "强"
    else -> "很强"
}

/**
 * 熵值取数（绑定命名待生成后核对，见文件头）：现按 UDL 命名空间函数的 UniFFI 惯例调用。
 * 校准点集中在此处与本文件 import 两处。
 */
private fun entropyBitsOf(spec: GeneratorSpec): UInt = generatorEntropyBits(spec)

private fun entropyBitsOf(spec: PassphraseSpec): UInt = passphraseEntropyBits(spec)
